#!/usr/bin/env python3
"""Extract the lookup tables Shruthi's oscillators/envelopes need from
shruthi/resources.cc into a plain C header (no PROGMEM)."""
import re, sys
src = open(sys.argv[1]).read()
want = {
 'lut_res_oscillator_increments':'uint16_t','lut_res_env_portamento_increments':'uint16_t',
 'lut_res_lfo_increments':'uint16_t','lut_res_fm_frequency_ratios':'uint16_t',
 'wav_res_sine':'uint8_t','wav_res_env_expo':'uint8_t','wav_res_distortion':'uint8_t',
 'wav_res_waves':'uint8_t','wav_res_wavetables':'uint8_t',
 'wav_res_bandlimited_triangle_0':'uint8_t',
 'wav_res_formant_sine':'uint8_t','wav_res_formant_square':'uint8_t','wav_res_vowel_data':'uint8_t',
}
for i in range(7): want['wav_res_bandlimited_square_%d'%i]='uint8_t'
for i in range(6): want['wav_res_bandlimited_saw_%d'%i]='uint8_t'
for i in (3,4,5): want['wav_res_bandlimited_triangle_%d'%i]='uint8_t'
out=['/* Generated by gen_tables.py from shruthi/resources.cc -- do not edit.',
     ' * Data (c) Emilie Gillet, GPL-3.0-or-later (Shruthi-1). */',
     '#ifndef SHRUTHI_TABLES_H','#define SHRUTHI_TABLES_H','#include <stdint.h>']
found=[]
for name,typ in want.items():
    m=re.search(r'const\s+prog_u?int\d+_t\s+%s\[\]\s*PROGMEM\s*=\s*\{(.*?)\};'%name, src, re.S)
    if not m: print('missing',name,file=sys.stderr); continue
    body=re.sub(r'//[^\n]*','',m.group(1))
    vals=[v.strip() for v in body.replace('\n',' ').split(',') if v.strip()]
    out.append('static const %s %s[%d] = {'%(typ,name,len(vals)))
    for i in range(0,len(vals),16): out.append('  '+', '.join(vals[i:i+16])+',')
    out.append('};'); found.append((name,len(vals)))
out.append('#endif')
open(sys.argv[2],'w').write('\n'.join(out)+'\n')
for n,l in found: print(n,l)
